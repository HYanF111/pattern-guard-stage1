def get_pattern_risk_tips(pattern_name: str | None) -> list[str]:
    """
    根据纹样名称获取专项风险提示。
    支持档案名称与专项规则名称不完全一致的情况。
    未收录纹样返回通用提示。
    """

    if not pattern_name:
        return [
            "当前为自由上传纹样，系统尚未匹配到具体传统纹样档案。",
            "建议进一步核实纹样来源、原始创作者及图片授权情况。"
        ]

    # 去除名称前后的空格
    name = pattern_name.strip()

    # 先尝试完全匹配
    if name in PATTERN_RULES:
        return PATTERN_RULES[name]

    # 兼容带有括号说明的纹样名称
    aliases = {
        "龙纹（应龙）": "龙纹",
        "龙纹(应龙)": "龙纹",
    }

    matched_name = aliases.get(name)

    if matched_name and matched_name in PATTERN_RULES:
        return PATTERN_RULES[matched_name]

    # 未匹配时返回通用提示
    return [
        f"当前纹样“{pattern_name}”尚未收录专项规则。",
        "建议核实纹样来源、素材授权情况及相关在先权利。"
    ]